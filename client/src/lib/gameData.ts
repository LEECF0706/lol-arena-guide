// 根据英雄名称搜索
export function searchChampions(query: string): Champion[] {
  const q = query.toLowerCase();
  return champions.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.nameCN.toLowerCase().includes(q) ||
      c.role.some((r) => r.toLowerCase().includes(q)) ||
      c.tags.some((t) => t.toLowerCase().includes(q))
  );
}

// 根据海克斯名称搜索
export function searchAugments(query: string): Augment[] {
  const q = query.toLowerCase();
  return augments.filter(
    (a) =>
      a.name.toLowerCase().includes(q) ||
      a.nameCN.toLowerCase().includes(q) ||
      a.tags.some((t) => t.toLowerCase().includes(q)) ||
      a.tier.toLowerCase().includes(q)
  );
}

// 获取英雄的最佳海克斯详情
export function getChampionBestAugments(champion: Champion): Augment[] {
  return champion.bestAugments
    .map((id) => augments.find((a) => a.id === id))
    .filter(Boolean) as Augment[];
}

// 获取英雄的推荐海克斯详情
export function getChampionGoodAugments(champion: Champion): Augment[] {
  return champion.goodAugments
    .map((id) => augments.find((a) => a.id === id))
    .filter(Boolean) as Augment[];
}

// 根据标签筛选英雄
export function filterChampionsByTag(tag: string): Champion[] {
  return champions.filter((c) => c.tags.includes(tag));
}

// 根据等级筛选海克斯
export function filterAugmentsByTier(tier: 'silver' | 'gold' | 'prismatic'): Augment[] {
  return augments.filter((a) => a.tier === tier);
}

// 获取海克斯等级排名
export function getAugmentTierRank(augmentId: string): string {
  for (const tier of tierList) {
    if (tier.augments.includes(augmentId)) {
      return tier.tier;
    }
  }
  return 'C';
}
